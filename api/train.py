"""Training CLI.

    python -m api.train --config api/configs/baseline.yaml

Trains one configuration under the shared compute budget, writes the best
checkpoint to models/, and records a row in `runs` so the README comparison
table can be generated by SQL rather than typed by hand.

MATCHED BUDGET. Every config in the comparison gets the same seed, the same
20,000-image subsample in the same order, the same 12 epochs, and the same
batch size. Nothing stops early: an early-stopping run would have used less
compute than its siblings, which would make "the improved model is better" a
claim about training length rather than about architecture. The best-validation
checkpoint is kept, but the full budget is always spent.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

import joblib
import numpy as np
import torch
import yaml
from sklearn.metrics import confusion_matrix, precision_recall_fscore_support
from supabase import create_client
from torch import nn

from api.models import build_model, count_params, describe
from shared.fashion import CLASS_NAMES, N_CLASSES, load_splits, to_tensor

MODELS_DIR = Path("models")


# ---------------------------------------------------------------------------
# Augmentation
# ---------------------------------------------------------------------------
def augment(xb: torch.Tensor, generator: torch.Generator) -> torch.Tensor:
    """Random horizontal flip + random 28x28 crop from a 2px-padded image.

    Written by hand rather than with torchvision.transforms so the training
    path has one less dependency to pin, and so the exact operations are
    visible: these two are the entirety of what the `augmentation: true` flag
    turns on, and the ablation's job is to measure precisely them.

    Horizontal flip is safe for Fashion-MNIST -- a mirrored shirt is still a
    shirt. It would NOT be safe for a dataset with chirality (text, digits
    like 2 vs 5 in some fonts, left/right medical scans), which is worth
    remembering before reusing this.
    """
    n = xb.shape[0]

    flip = torch.rand(n, generator=generator) < 0.5
    xb = torch.where(flip[:, None, None, None], torch.flip(xb, dims=[3]), xb)

    pad = 2
    padded = nn.functional.pad(xb, (pad, pad, pad, pad), mode="constant", value=0.0)
    out = torch.empty_like(xb)
    offsets = torch.randint(0, 2 * pad + 1, (n, 2), generator=generator)
    for i in range(n):
        r, c = int(offsets[i, 0]), int(offsets[i, 1])
        out[i] = padded[i, :, r : r + xb.shape[2], c : c + xb.shape[3]]
    return out


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------
@torch.no_grad()
def evaluate(model: nn.Module, x: torch.Tensor, y: np.ndarray, batch_size: int = 512):
    """Return (loss, accuracy, predictions, probabilities) on a split."""
    model.eval()
    loss_fn = nn.CrossEntropyLoss(reduction="sum")
    total_loss, preds, probs = 0.0, [], []
    y_t = torch.from_numpy(y)
    for start in range(0, len(x), batch_size):
        xb = x[start : start + batch_size]
        yb = y_t[start : start + batch_size]
        logits = model(xb)
        total_loss += loss_fn(logits, yb).item()
        p = torch.softmax(logits, dim=1)
        probs.append(p.numpy())
        preds.append(p.argmax(dim=1).numpy())
    preds_arr = np.concatenate(preds)
    return (
        total_loss / len(x),
        float((preds_arr == y).mean()),
        preds_arr,
        np.concatenate(probs),
    )


def per_class_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> list[dict]:
    p, r, f1, support = precision_recall_fscore_support(
        y_true, y_pred, labels=list(range(N_CLASSES)), zero_division=0
    )
    return [
        {
            "class_id": i,
            "class_name": CLASS_NAMES[i],
            "precision": float(p[i]),
            "recall": float(r[i]),
            "f1": float(f1[i]),
            "support": int(support[i]),
        }
        for i in range(N_CLASSES)
    ]


# ---------------------------------------------------------------------------
# Supabase
# ---------------------------------------------------------------------------
def get_client():
    url = os.environ.get("SUPABASE_URL")
    key = os.environ.get("SUPABASE_SERVICE_KEY")
    if not url or not key:
        sys.exit("SUPABASE_URL and SUPABASE_SERVICE_KEY must be set in .env")
    return create_client(url, key)


def ensure_dataset_row(client, n_train: int, seed: int) -> int:
    """`runs.dataset_id` is a NOT NULL foreign key into `datasets`, which the
    template designed for synthetic datasets regenerated from a seed. The real
    images live on disk and are never uploaded, so we keep one descriptive row
    describing the Fashion-MNIST subsample and point every run at it."""
    existing = client.table("datasets").select("id").eq("name", "fashion-mnist").limit(1).execute()
    if existing.data:
        return existing.data[0]["id"]
    created = client.table("datasets").insert({
        "name": "fashion-mnist",
        "n_rows": n_train,
        "img_size": 28,
        "n_classes": N_CLASSES,
        "noise": 0.0,          # no synthetic noise; the column is from the template
        "seed": seed,
    }).execute()
    return created.data[0]["id"]


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True)
    parser.add_argument("--no-db", action="store_true",
                        help="train and checkpoint without writing a runs row")
    args = parser.parse_args()

    cfg = yaml.safe_load(Path(args.config).read_text())
    name = cfg["name"]
    seed = int(cfg.get("seed", 42))

    print(f"\n=== {name} ===")
    print(f"arch={cfg['arch']}  bn={cfg.get('batch_norm')}  dropout={cfg.get('dropout')}  "
          f"aug={cfg.get('augmentation')}  wd={cfg.get('weight_decay')}  "
          f"sched={cfg.get('lr_schedule')}")

    torch.manual_seed(seed)
    np.random.seed(seed)
    gen = torch.Generator().manual_seed(seed)

    x_tr_u8, y_tr, x_va_u8, y_va, x_te_u8, y_te = load_splits(seed=seed)
    x_tr = to_tensor(x_tr_u8)
    x_va = to_tensor(x_va_u8)
    x_te = to_tensor(x_te_u8)
    y_tr_t = torch.from_numpy(y_tr)
    print(f"train {len(x_tr):,}  val {len(x_va):,}  test {len(x_te):,}")

    model = build_model(cfg)
    n_params = count_params(model)
    arch_str = describe(model)
    print(f"{n_params:,} params | {arch_str}")

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=float(cfg["lr"]),
        weight_decay=float(cfg.get("weight_decay", 0.0)),
    )
    epochs = int(cfg["epochs"])
    scheduler = None
    if cfg.get("lr_schedule") == "cosine":
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs)

    loss_fn = nn.CrossEntropyLoss()
    batch_size = int(cfg["batch_size"])
    use_aug = bool(cfg.get("augmentation", False))

    history, best_val_acc, best_state, best_epoch = [], -1.0, None, 0
    t0 = time.time()

    for epoch in range(1, epochs + 1):
        model.train()
        perm = torch.randperm(len(x_tr), generator=gen)
        running_loss, correct = 0.0, 0

        for start in range(0, len(x_tr), batch_size):
            idx = perm[start : start + batch_size]
            xb, yb = x_tr[idx], y_tr_t[idx]
            if use_aug:
                xb = augment(xb, gen)

            optimizer.zero_grad()
            logits = model(xb)
            loss = loss_fn(logits, yb)
            loss.backward()
            optimizer.step()

            running_loss += loss.item() * len(xb)
            correct += int((logits.argmax(dim=1) == yb).sum())

        if scheduler is not None:
            scheduler.step()

        train_loss = running_loss / len(x_tr)
        train_acc = correct / len(x_tr)
        val_loss, val_acc, _, _ = evaluate(model, x_va, y_va)

        history.append({
            "epoch": epoch,
            "train_loss": round(train_loss, 5),
            "train_acc": round(train_acc, 5),
            "val_loss": round(val_loss, 5),
            "val_acc": round(val_acc, 5),
            "lr": round(optimizer.param_groups[0]["lr"], 6),
        })
        print(f"  epoch {epoch:2d}  train_loss {train_loss:.4f}  train_acc {train_acc:.4f}  "
              f"val_loss {val_loss:.4f}  val_acc {val_acc:.4f}")

        # Keep the best weights, but never stop early -- the budget is matched.
        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
            best_epoch = epoch

    train_seconds = time.time() - t0
    model.load_state_dict(best_state)

    test_loss, test_acc, test_preds, _ = evaluate(model, x_te, y_te)
    cm = confusion_matrix(y_te, test_preds, labels=list(range(N_CLASSES)))
    per_class = per_class_metrics(y_te, test_preds)
    macro_f1 = float(np.mean([c["f1"] for c in per_class]))

    print(f"\nTest ({len(x_te):,} held-out images)")
    print(f"  top-1 accuracy {test_acc:.4f}   macro-F1 {macro_f1:.4f}")
    print(f"  best val {best_val_acc:.4f} at epoch {best_epoch}   "
          f"trained in {train_seconds:.0f}s")
    worst = sorted(per_class, key=lambda c: c["recall"])[:3]
    print("  weakest classes by recall: " +
          ", ".join(f"{c['class_name']} {c['recall']:.3f}" for c in worst))

    MODELS_DIR.mkdir(exist_ok=True)
    ckpt_path = MODELS_DIR / f"{name}.joblib"
    joblib.dump({
        "state_dict": model.state_dict(),
        "config": cfg,
        "arch": arch_str,
        "n_params": n_params,
        "metrics": {"test_accuracy": test_acc, "macro_f1": macro_f1, "test_loss": test_loss},
        "history": history,
        "confusion": cm.tolist(),
        "per_class": per_class,
        "class_names": CLASS_NAMES,
        "torch_version": torch.__version__,
    }, ckpt_path)
    print(f"Saved {ckpt_path}")

    if args.no_db:
        print("--no-db: skipped the runs row")
        return

    client = get_client()
    dataset_id = ensure_dataset_row(client, len(x_tr), seed)
    row = {
        "dataset_id":        dataset_id,
        "config_name":       name,
        "architecture":      arch_str,
        "n_params":          n_params,
        "seed":              seed,
        "n_train":           len(x_tr),
        "n_val":             len(x_va),
        "n_test":            len(x_te),
        "lr":                float(cfg["lr"]),
        "batch_size":        batch_size,
        "epochs":            epochs,
        "augmentation":      use_aug,
        "batch_norm":        bool(cfg.get("batch_norm", False)),
        "dropout":           float(cfg.get("dropout", 0.0)),
        "weight_decay":      float(cfg.get("weight_decay", 0.0)),
        "lr_schedule":       cfg.get("lr_schedule"),
        "residual":          False,
        "accuracy":          test_acc,     # NOT NULL in the template schema
        "macro_f1":          macro_f1,     # NOT NULL in the template schema
        "test_accuracy":     test_acc,
        "best_val_accuracy": best_val_acc,
        "best_epoch":        best_epoch,
        "history":           history,
        "confusion":         cm.tolist(),
        "per_class":         per_class,
        "train_seconds":     round(train_seconds, 1),
        "notes":             cfg.get("notes", ""),
    }
    created = client.table("runs").insert(row).execute()
    print(f"Wrote runs row id={created.data[0]['id']}")


if __name__ == "__main__":
    main()