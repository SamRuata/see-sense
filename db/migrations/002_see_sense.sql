-- 002_see_sense.sql
-- Extends the See-Sense template schema for the real assignment:
--   * a proper `predictions` table (the brief names it explicitly)
--   * `runs` columns for a baseline-vs-improved comparison with ablations
--   * `image_metadata` columns for channels and source
--
-- Apply AFTER 001_init.sql: Supabase -> SQL Editor -> New query -> paste -> Run.
--
-- PRIVACY INVARIANT (carried over from 001 and enforced here too): no raw image
-- bytes are ever written to Postgres. Only SHA-256 hashes, dimensions, and the
-- model's output. The Fashion-MNIST training data lives on disk at training
-- time and in the committed checkpoint's weights -- never in this database.

-- ---------------------------------------------------------------------------
-- runs: the template stores lr / batch_size / epochs / accuracy / macro_f1,
-- which describes ONE model. A baseline-vs-improved comparison with ablations
-- needs the architecture and every regularization switch recorded per run, so
-- the README's comparison table can be generated by a SQL query rather than
-- typed by hand.
-- ---------------------------------------------------------------------------
alter table runs add column if not exists config_name   text;
alter table runs add column if not exists architecture  text;      -- human-readable layer summary
alter table runs add column if not exists n_params      integer;
alter table runs add column if not exists seed          integer;
alter table runs add column if not exists n_train       integer;
alter table runs add column if not exists n_val         integer;
alter table runs add column if not exists n_test        integer;

-- Improvement techniques, one column each so an ablation is a WHERE clause.
alter table runs add column if not exists augmentation  boolean default false;
alter table runs add column if not exists batch_norm    boolean default false;
alter table runs add column if not exists dropout       double precision default 0.0;
alter table runs add column if not exists weight_decay  double precision default 0.0;
alter table runs add column if not exists lr_schedule   text;       -- null | 'cosine' | 'step'
alter table runs add column if not exists residual      boolean default false;

-- Richer metrics. Curves and per-class numbers are arrays, so they are stored
-- as jsonb rather than exploded into their own tables -- they are only ever
-- read back whole, to draw a plot.
alter table runs add column if not exists test_accuracy      double precision;
alter table runs add column if not exists best_val_accuracy  double precision;
alter table runs add column if not exists best_epoch         integer;
alter table runs add column if not exists history            jsonb;  -- [{epoch, train_loss, train_acc, val_loss, val_acc}]
alter table runs add column if not exists confusion          jsonb;  -- 10x10 nested array, test split
alter table runs add column if not exists per_class          jsonb;  -- [{class_name, precision, recall, f1, support}]
alter table runs add column if not exists train_seconds      double precision;
alter table runs add column if not exists notes              text;

create index if not exists idx_runs_config_name on runs (config_name);

-- ---------------------------------------------------------------------------
-- predictions: one row per served /predict call.
--
-- The template logs to `image_metadata` only, which mixes two concerns: what
-- the image was (shape, hash) and what the model said about it. The brief names
-- `predictions` separately, and the Recent Classifications tab needs to join
-- predictions -> runs to show which model served each call. Keeping them apart
-- also means a future model re-scoring the same image adds a prediction row
-- without duplicating the image's metadata.
--
-- top5 is jsonb: [{"class_name": "Pullover", "proba": 0.81}, ...]
-- true_label is nullable -- an uploaded image has no ground truth, only the
-- held-out gallery and sample endpoints do.
-- ---------------------------------------------------------------------------
create table if not exists predictions (
    id               bigint generated always as identity primary key,
    served_by_run_id bigint      not null references runs (id) on delete cascade,
    image_hash       text        not null,              -- sha256 of the input bytes
    predicted_label  integer     not null,
    predicted_class  text        not null,
    predicted_proba  double precision not null,         -- confidence in the top class
    top5             jsonb       not null,
    true_label       integer,                           -- null for user uploads
    true_class       text,
    correct          boolean,                           -- null when true_label is null
    source           text        not null default 'upload',  -- 'upload' | 'sample' | 'gallery'
    latency_ms       integer,
    created_at       timestamptz not null default now()
);

create index if not exists idx_predictions_run_id     on predictions (served_by_run_id);
create index if not exists idx_predictions_created_at on predictions (created_at desc);
create index if not exists idx_predictions_class      on predictions (predicted_class);
create index if not exists idx_predictions_hash       on predictions (image_hash);

-- ---------------------------------------------------------------------------
-- image_metadata: keep the template's table, add channels + source so a
-- grayscale upload and an RGB one are distinguishable in an audit. Still no
-- pixels: sha256 + dimensions + the label only.
-- ---------------------------------------------------------------------------
alter table image_metadata add column if not exists channels   integer default 1;
alter table image_metadata add column if not exists source     text default 'upload';
alter table image_metadata add column if not exists byte_size  integer;

create index if not exists idx_image_metadata_sha256 on image_metadata (sha256);

-- ---------------------------------------------------------------------------
-- Row Level Security.
--
-- 001 enabled RLS everywhere and gave anon SELECT on `runs`. The Recent
-- Classifications tab reads `predictions` directly with the anon key to build
-- its table and class-distribution histogram, so anon needs SELECT there too.
-- Writes remain server-side: the API holds the service-role key, which bypasses
-- RLS entirely. Anon is never granted insert, update or delete on anything.
-- ---------------------------------------------------------------------------
alter table predictions enable row level security;

drop policy if exists "anon can read predictions" on predictions;
create policy "anon can read predictions"
    on predictions for select
    to anon
    using (true);

-- image_metadata stays server-side only: it is keyed by image hash, and the
-- public wall has no reason to enumerate hashes. The UI gets everything it
-- needs from `predictions`.